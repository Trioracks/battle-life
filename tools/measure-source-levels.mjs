// Build-time only: input loudness measurement, never loudnorm compression/output.
import {writeFile,mkdir} from 'node:fs/promises';
import {spawnSync} from 'node:child_process';
import {BEGINNER_BANK,USER_DRUM_BANK} from '../src/beat-beginner-bank.js';
const targets={drums:-30,theme:-27,arrangement:-28.5},measurements={},gains={};
for(const part of [...BEGINNER_BANK,...USER_DRUM_BANK]){
 const r=spawnSync(process.env.FFMPEG_PATH||'ffmpeg',['-hide_banner','-nostats','-threads','1','-i',part.path,'-filter_threads','1','-af','loudnorm=I=-23:TP=-1:LRA=7:print_format=json','-f','null','NUL'],{windowsHide:true,maxBuffer:1000000});
 if(r.status!==0)throw Error(String(r.stderr));
 const json=String(r.stderr).match(/\{\s*"input_i"[\s\S]*?\}/)?.[0];if(!json)throw Error('No loudness measurement: '+part.id);
 const m=JSON.parse(json),lufs=Number(m.input_i),truePeak=Number(m.input_tp);
 if(!Number.isFinite(lufs)||!Number.isFinite(truePeak))throw Error('Silent/invalid source: '+part.id);
 // Leave transient dynamics intact, including unusually sparse parts.
 const wanted=targets[part.kind]-lufs,gainDb=Math.min(wanted,-10-truePeak);
 gains[part.id]=Number(gainDb.toFixed(2));
 measurements[part.id]={lufs,truePeak,targetLufs:targets[part.kind],gainDb:gains[part.id],peakLimited:gainDb<wanted};
}
await mkdir('artifacts/audio-levels',{recursive:true});
await writeFile('artifacts/audio-levels/source-measurements.json',JSON.stringify(measurements,null,2)+'\n');
await writeFile('src/source-levels-v1.js','// Generated by tools/measure-source-levels.mjs. Versioned calibration: do not overwrite after release.\nexport const SOURCE_GAINS_DB=Object.freeze('+JSON.stringify(gains,null,2)+');\n');
console.log('Measured and calibrated '+Object.keys(gains).length+' sources without modifying audio files.');
